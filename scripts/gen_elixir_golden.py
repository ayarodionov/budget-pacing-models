"""Generate elixir/pacing_math_test.exs: expected values computed with scipy.

Run: uv run python scripts/gen_elixir_golden.py
"""
from pathlib import Path

import numpy as np
from scipy import special

f = lambda v: f"{float(v):.17e}"  # noqa: E731  Elixir-compatible float literal
rng = np.random.default_rng(2026)

lg = [1e-3, 0.1, 0.5, 1.0, 1.5, 2.0, 3.7, 10.0, 171.3, 1e3, 2.5e4, 1e6]
bi = list(zip(np.floor(np.exp(rng.uniform(0, np.log(2e4), 40))) + 1,
              np.exp(rng.uniform(np.log(0.5), np.log(2e4), 40)),
              np.exp(rng.uniform(np.log(1e-7), np.log(0.999), 40))))
gi = list(zip(np.floor(np.exp(rng.uniform(0, np.log(2e4), 30))) + 1, [None] * 30))
gi = [(a, a * np.exp(rng.uniform(np.log(0.05), np.log(3.0)))) for a, _ in gi]
# controller-like cases: alpha = 1 + spend seen, beta = exposure seen, v = in-flight exposure
nb = []
for alpha, beta, v in [(5001.0, 50.0, 0.5), (801.0, 8.0, 0.42), (101.0, 1.0, 0.35), (3.0, 0.02, 0.07)]:
    mean = alpha * v / beta
    for m in np.unique(np.round(mean + np.array([-0.5, 0, 1, 2, 3, 4, 5]) * np.sqrt(mean * (1 + v / beta)))):
        nb.append((m, alpha, beta, v))
pt = [(m, mu) for mu in (0.5, 7.0, 42.0, 400.0) for m in np.unique(np.round(mu + np.array([0, 1, 3, 5]) * np.sqrt(mu)))]

lines = ["# Generated by scripts/gen_elixir_golden.py from scipy - do not edit.",
         "# Run: make -C elixir test   (tests PacingMath, and PacingMathNif if the NIF is built)",
         "ExUnit.start()", "", "defmodule PacingMathTest do", "  use ExUnit.Case, async: true", "",
         "  @rel 1.0e-9",
         "  @impls Enum.filter([PacingMath, PacingMathNif], &Code.ensure_loaded?/1)", "",
         '  IO.puts("testing: #{inspect(@impls)}")', "",
         "  defp close(got, want) when want == 0.0, do: abs(got) < 1.0e-12",
         "  defp close(got, want) when abs(want) < 1.0e-280, do: abs(got) < 1.0e-270",
         "  defp close(got, want), do: abs(got - want) / abs(want) < @rel", ""]

def block(name, call, cases, want):
    lines.append(f"  @{name} [")
    for c, w in zip(cases, want):
        lines.append("    {" + ", ".join(f(x) for x in c) + ", " + f(w) + "},")
    lines.append("  ]"); lines.append("")
    args = ", ".join(f"x{i}" for i in range(len(cases[0])))
    lines.append(f'  test "{name}" do')
    lines.append(f"    for mod <- @impls, {{{args}, want}} <- @{name} do")
    lines.append(f"      got = mod.{call}({args})")
    lines.append(f'      assert close(got, want), "#{{inspect(mod)}}.{call}#{{inspect({{{args}}})}} = #{{got}}, want #{{want}}"')
    lines.append("    end"); lines.append("  end"); lines.append("")

block("lgamma_cases", "lgamma", [(x,) for x in lg], special.gammaln(lg))
block("betainc_cases", "betainc", bi, [special.betainc(a, b, x) for a, b, x in bi])
block("gammainc_cases", "gammainc_lower", gi, [special.gammainc(a, x) for a, x in gi])
block("nb_tail_cases", "nb_tail", nb, [special.betainc(m + 1, a, v / (b + v)) for m, a, b, v in nb])
block("poisson_tail_cases", "poisson_tail", pt, [special.gammainc(m + 1, mu) for m, mu in pt])

lines += ['  test "edge cases" do', "    for mod <- @impls do",
          "    assert PacingMath.nb_tail(-1, 2.0, 1.0, 1.0) == 1.0",
          "    assert PacingMath.nb_tail(3, 2.0, 1.0, 0.0) == 0.0",
          "    assert PacingMath.poisson_tail(-0.5, 2.0) == 1.0",
          "    assert PacingMath.poisson_tail(3, 0.0) == 0.0",
          "    assert PacingMath.betainc(2.0, 3.0, 0.0) == 0.0",
          "    assert PacingMath.betainc(2.0, 3.0, 1.0) == 1.0",
          "    end",
          "    assert PacingMath.log1p(1.0e-17) == 1.0e-17",
          "  end", "",
          '  test "NIF agrees with pure Elixir on random controller-like arguments" do',
          "    if PacingMathNif in @impls do",
          "      :rand.seed(:exsss, {1, 2, 3})",
          "      for _ <- 1..5000 do",
          "        alpha = 1.0 + :rand.uniform() * 2.0e4",
          "        beta = 0.01 + :rand.uniform() * 500.0",
          "        v = :rand.uniform() * 5.0",
          "        m = Float.floor(alpha * v / beta * (0.5 + :rand.uniform() * 1.5))",
          "        a = PacingMath.nb_tail(m, alpha, beta, v)",
          "        b = PacingMathNif.nb_tail(m, alpha, beta, v)",
          "        assert a == b or abs(a - b) <= 1.0e-11 * abs(a), \"nb_tail(#{m}, #{alpha}, #{beta}, #{v}): #{a} vs #{b}\"",
          "      end",
          "    end",
          "  end", "end", ""]
Path("elixir/pacing_math_test.exs").write_text("\n".join(lines))
print(f"{len(lg)} lgamma, {len(bi)} betainc, {len(gi)} gammainc, {len(nb)} nb_tail, {len(pt)} poisson_tail cases")
