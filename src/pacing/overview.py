"""One chart comparing the three models in the default scenario (for README.md).

Run:  uv run python -m pacing.overview [--quick]
      -> results/overview.md, results/overview.png
"""

from __future__ import annotations

import argparse
from dataclasses import replace

import numpy as np

from .backstop import simulate_with_backstop
from .controllers import BayesRiskController, NaiveController
from .experiments import AQUA, BLUE, INK2, ORANGE, OUT, plt
from .model import Scenario, simulate

RS = (0.1, 0.5, 1.0)
MODELS = (
    "Probabilistic\nε = 10⁻³",
    "Token cap (a)\nreports after 5 s",
    "Token cap (a)\nreports after 30 s",
    "Token cap (b)\nno reports",
)
SHORT = ("Probabilistic", "Cap (a)\n5 s", "Cap (a)\n30 s", "Cap (b)")


def run(n: int) -> dict[str, dict[float, tuple[float, int, int]]]:
    """model -> r -> (mean underspend %, overspends, runs)."""
    base = Scenario()
    k = base.spend_rate_at_p1  # k = lambda * r kept at 100 while r varies
    out: dict[str, dict[float, tuple[float, int, int]]] = {m: {} for m in MODELS}
    for r in RS:
        scn = replace(base, request_rate=k / r, realization=r)
        naive = lambda: NaiveController(scn.center_view(), prior_mean=k)  # noqa: E731
        results = {
            MODELS[0]: simulate(scn, BayesRiskController(scn.center_view(), prior_mean=k, eps=1e-3), n, seed=7),
            MODELS[1]: simulate_with_backstop(scn, naive(), n, failure_delay=5.0, seed=7),
            MODELS[2]: simulate_with_backstop(scn, naive(), n, failure_delay=30.0, seed=7),
            MODELS[3]: simulate_with_backstop(scn, naive(), n, seed=7, mode="grants", grant_share=0.5),
        }
        for m, res in results.items():
            s = res.summary(scn.budget)
            out[m][r] = (s["mean_underspend_pct"], int(res.overspent.sum()), n)
    return out


def chart(data) -> None:
    fig, (ax_u, ax_o) = plt.subplots(1, 2, figsize=(12, 4.2), gridspec_kw={"width_ratios": [2, 1]})
    x = np.arange(len(MODELS))
    w = 0.26
    for i, (r, color) in enumerate(zip(RS, (BLUE, ORANGE, AQUA))):
        vals = [data[m][r][0] for m in MODELS]
        bars = ax_u.bar(x + (i - 1) * w, vals, w * 0.92, color=color, label=f"r = {r:g}")
        ax_u.bar_label(bars, fmt="%.2f", fontsize=7, color=INK2, padding=2)
    ax_u.set_xticks(x, MODELS, fontsize=8)
    ax_u.set(title="Underspend (lower is better)", ylabel="mean underspend, % of budget")
    ax_u.legend(title="share of bids charged", fontsize=8, title_fontsize=8)

    rates = []
    for m in MODELS:
        over = sum(data[m][r][1] for r in RS)
        runs = sum(data[m][r][2] for r in RS)
        rates.append(100 * over / runs)
    bars = ax_o.bar(x, rates, 0.6, color=BLUE)
    ax_o.bar_label(bars, labels=[f"{v:.2f} %" if v else "0" for v in rates],
                   fontsize=7, color=INK2, padding=2)
    ax_o.set_xticks(x, SHORT, fontsize=8)
    ax_o.set(title="Overspend (all r pooled)", ylabel="runs that overspent, %",
             ylim=(0, max(rates) * 1.6 or 1))
    for ax in (ax_u, ax_o):
        ax.set_axisbelow(True)
        ax.grid(axis="x", visible=False)

    fig.suptitle("Three models, default scenario (B = 5000, T = 1 h, d = 30 s, k = λ·r = 100)",
                 x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(OUT / "overview.png", dpi=140)
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    n = 3_000 if ap.parse_args().quick else 20_000
    OUT.mkdir(exist_ok=True)
    data = run(n)
    chart(data)
    md = ["# Results: the three models side by side", "",
          "Generated by `uv run python -m pacing.overview`. Default scenario (B = 5000, T = 3600 s, "
          "d = 30 s, step = 5 s), k = λ·r = 100 kept fixed while r varies. "
          f"{n} runs per cell. Token-cap rows use plain pacing with the cap "
          "(*cap only* in the token-cap results). Details: "
          "[probabilistic](probabilistic.md), [token cap (a)](token-cap-a.md), "
          "[token cap (b)](token-cap-b.md).", "",
          "| model | " + " | ".join(f"underspend %, r = {r:g}" for r in RS) + " | overspends / runs |",
          "|---|" + "---|" * (len(RS) + 1)]
    for m in MODELS:
        over = sum(data[m][r][1] for r in RS)
        runs = sum(data[m][r][2] for r in RS)
        cells = " | ".join(f"{data[m][r][0]:.2f}" for r in RS)
        md.append(f"| {m.replace(chr(10), ', ')} | {cells} | {over} / {runs} |")
    md += ["", "![The three models side by side](overview.png)", ""]
    (OUT / "overview.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
