"""Experiments for the seasonal models (traffic that varies with time of day and day of week).

Run:  uv run python -m pacing.seasonal_experiments [--quick]
      -> results/seasonal/{probabilistic,token-cap-a,token-cap-b}.md and charts
"""

from __future__ import annotations

import argparse
import time
from dataclasses import replace
from pathlib import Path

import numpy as np

from .backstop import simulate_with_backstop
from .experiments import BLUE, INK2, ORANGE, AQUA, YELLOW, plt
from .model import simulate
from .seasonal import DAY, SeasonalController, SeasonalPacer, month_scenario, step_profile, traffic_target

OUT = Path("results") / "seasonal"
EPS = 0.01

HEADER = ("| setting | P(overspend) | 95% upper bound | worst overspend, units | mean underspend, units "
          "| mean underspend % | max deviation from the traffic target % |\n|---|---|---|---|---|---|---|")


def row(name, res, budget):
    s = res.summary(budget)
    over = res.final_spend - budget
    p = f"{s['overspend_prob']:.2e}" if s["overspend_prob"] else "0"
    return (f"| {name} | {p} | {s['overspend_prob_upper95']:.1e} | {max(0.0, float(over.max())):.0f} | "
            f"{s['mean_underspend_pct'] * budget / 100:.0f} | {s['mean_underspend_pct']:.4f} | "
            f"{s['mean_max_pace_dev_pct']:.2f} |")


class FullThrottle:
    """Adversarial controller: p = 1 always."""

    def reset(self, n):
        pass

    def decide(self, t, spend, exposure, inflight):
        return np.ones(spend.shape)


def probabilistic(n: int):
    scn = month_scenario()
    prof = step_profile(scn.horizon, scn.step)
    tgt = traffic_target(prof)
    wrong = step_profile(scn.horizon, scn.step, peak_hour=16.0, weekend=1.0)

    def ctl(sc, **kw):
        return SeasonalController(sc.center_view(), prior_mean=sc.spend_rate_at_p1, eps=EPS, **kw)

    rows = [
        ("constant traffic (reference)", scn, {}, dict()),
        ("traffic varies, profile known", scn, dict(profile=prof),
         dict(rate_profile=prof, center_profile=prof, target=tgt)),
        ("traffic varies, profile unknown", scn, {}, dict(rate_profile=prof, target=tgt)),
        ("profile unknown, risk check on the last 1 h", scn, dict(risk_half_life=3600.0),
         dict(rate_profile=prof, target=tgt)),
        ("profile unknown, risk check on the last 10 min", scn, dict(risk_half_life=600.0),
         dict(rate_profile=prof, target=tgt)),
        ("profile wrong (peak at 16 h, no weekend dip)", scn, dict(profile=wrong),
         dict(rate_profile=prof, center_profile=wrong, target=tgt)),
        ("profile wrong, risk check on the last 1 h", scn, dict(profile=wrong, risk_half_life=3600.0),
         dict(rate_profile=prof, center_profile=wrong, target=tgt)),
    ]
    # a campaign that ends at 08:00, when traffic is lowest
    trough = replace(scn, horizon=30 * DAY + 8 * 3600)
    prof_t = step_profile(trough.horizon, trough.step)
    tgt_t = traffic_target(prof_t)
    rows += [
        ("ends at 08:00 (low traffic), profile known", trough, dict(profile=prof_t),
         dict(rate_profile=prof_t, center_profile=prof_t, target=tgt_t)),
        ("ends at 08:00 (low traffic), profile unknown", trough, {}, dict(rate_profile=prof_t, target=tgt_t)),
    ]

    md = ["# Results: probabilistic controller, traffic that varies", "",
          "Model: [models/seasonal/probabilistic.md](../../models/seasonal/probabilistic.md). "
          "Generated by `uv run python -m pacing.seasonal_experiments`.", "",
          f"A 30-day campaign starting on a Monday at 00:00: B = {scn.budget:,} units, k0 = "
          f"{scn.spend_rate_at_p1:.0f} spends/s at p = 1 on average, control step {scn.step:.0f} s, "
          f"spend delay d = {scn.delay:.0f} s, ε = {EPS}. The traffic profile has a daily cycle "
          "(factor 1 ± 0.6, peak at 20:00) and quieter weekends (0.7). Pacing follows the traffic. "
          f"{n} runs per row. The deviation is measured against the traffic-following target.", "",
          HEADER]
    for name, sc, ckw, skw in rows:
        res = simulate(sc, ctl(sc, **ckw), n, seed=21, **skw)
        md.append(row(name, res, sc.budget))
    md.append("")

    # sample run for the chart: the first week
    c = ctl(scn, profile=prof)
    res = simulate(scn, c, 1, seed=22, keep=1, rate_profile=prof, center_profile=prof, target=tgt)
    _fig_profile(scn, prof, res, OUT / "probabilistic-week.png")
    md += ["![First week: traffic, p and spend rate](probabilistic-week.png)", ""]
    md += even_section(scn, prof, wrong, n)
    return md


HEADER_EVEN = ("| setting | P(overspend) | worst overspend, units | mean underspend, units | max deviation from "
               "even spending % | p range (days 1-29, one run) | share of steps at p = 1 | p messages per hour "
               "(2 % threshold) |\n|---|---|---|---|---|---|---|---|")


def even_section(scn, prof, wrong, n):
    """Spending evenly in time instead of following the traffic."""
    big = replace(scn, budget=50 * scn.budget)
    rows = [
        ("follow the traffic, profile known (for comparison)", scn, dict(profile=prof),
         dict(rate_profile=prof, center_profile=prof)),
        ("even in time, profile known", scn, dict(profile=prof, pace_goal="time"),
         dict(rate_profile=prof, center_profile=prof)),
        ("even in time, profile unknown, current rate from the last 1 h", scn,
         dict(pace_goal="time", risk_half_life=3600.0), dict(rate_profile=prof)),
        ("even in time, profile unknown, current rate from the last 10 min", scn,
         dict(pace_goal="time", risk_half_life=600.0), dict(rate_profile=prof)),
        ("even in time, profile wrong", scn, dict(profile=wrong, pace_goal="time"),
         dict(rate_profile=prof, center_profile=wrong)),
        ("budget × 50: even in time, profile known", big, dict(profile=prof, pace_goal="time"),
         dict(rate_profile=prof, center_profile=prof)),
        ("budget × 50: follow the traffic, profile known", big, dict(profile=prof),
         dict(rate_profile=prof, center_profile=prof)),
    ]
    hours = scn.horizon / 3600
    lo, hi = int(DAY / scn.step), int(29 * DAY / scn.step)
    md = ["## Spending evenly in time", "",
          "The pacing goal changes from following the traffic to a constant spend rate: "
          "p = (budget left / time left) / (current spend rate at p = 1), so p is high in quiet "
          "hours and low in busy ones. Without a profile, the current rate comes from recent data. "
          "If a quiet hour cannot keep up even at p = 1, the shortfall raises the target rate for "
          "the rest of the campaign (catch-up). Deviation is measured against the even-in-time line. "
          f"All rows send p only when it changes by more than 2 %. {n} runs per row.", "", HEADER_EVEN]
    sample = {}
    for name, sc, ckw, skw in rows:
        c = SeasonalController(sc.center_view(), prior_mean=sc.spend_rate_at_p1, eps=EPS,
                               broadcast_threshold=0.02, **ckw)
        res = simulate(sc, c, n, seed=24, keep=1, **skw)
        s = res.summary(sc.budget)
        over = res.final_spend - sc.budget
        pp = res.traj_p[0][lo:hi]
        p_ = f"{s['overspend_prob']:.2e}" if s["overspend_prob"] else "0"
        md.append(f"| {name} | {p_} | {max(0.0, float(over.max())):.0f} | "
                  f"{s['mean_underspend_pct'] * sc.budget / 100:.0f} | {s['mean_max_pace_dev_pct']:.2f} | "
                  f"{pp.min():.4f}–{pp.max():.4f} | {(pp > 0.999).mean():.0%} | {c.broadcasts.mean() / hours:.1f} |")
        if name.startswith("even in time, profile known"):
            sample = res
    md.append("")
    _fig_profile(scn, prof, sample, OUT / "probabilistic-even-week.png",
                 p_title="p is high in quiet hours and low in busy ones",
                 spend_title="Spend is (almost) flat")
    md += ["![First week, even in time: traffic, p and spend rate](probabilistic-even-week.png)", ""]
    return md


def _fig_profile(scn, prof, res, path, p_title="p stays almost constant: pacing follows the traffic",
                 spend_title="Spend follows the traffic"):
    week = int(7 * DAY / scn.step)
    t = np.arange(week) * scn.step / DAY
    spend = np.diff(res.traj_spend[0][: week + 1]) / scn.step
    p = res.traj_p[0][:week]
    fig, axes = plt.subplots(3, 1, figsize=(10, 7), sharex=True)
    axes[0].plot(t, prof[:week], color=INK2, lw=1)
    axes[0].set(ylabel="traffic factor s(t)", title="Traffic profile: daily cycle, quieter weekend")
    axes[1].plot(t, p, color=BLUE, lw=1)
    axes[1].set(ylabel="broadcast p", title=p_title)
    hourly = spend.reshape(-1, 60).mean(axis=1) if week % 60 == 0 else spend
    axes[2].plot(np.arange(len(hourly)) * (60 * scn.step) / DAY, hourly, color=ORANGE, lw=1)
    axes[2].set(ylabel="spend, units/s (hourly mean)", xlabel="day of the campaign (Monday = 0)",
                title=spend_title)
    for ax in axes:
        ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def caps(mode: str, n: int):
    base = month_scenario()
    prof = step_profile(base.horizon, base.step)
    tgt = traffic_target(prof)
    if mode == "reports":
        variants = [("failure reports after 30 s", dict(failure_delay=30.0)),
                    ("failure reports after 10 min", dict(failure_delay=600.0))]
        title, model = "token cap, version (a)", "token-cap-a"
    else:
        variants = [("grant share 0.5", dict(mode="grants", grant_share=0.5))]
        title, model = "token cap, version (b)", "token-cap-b"
    md = [f"# Results: {title}, traffic that varies", "",
          f"Model: [models/seasonal/{model}.md](../../models/seasonal/{model}.md). "
          "Generated by `uv run python -m pacing.seasonal_experiments`.", "",
          "The same 30-day campaign as for the probabilistic controller. Plain pacing that follows "
          "the traffic (with the profile known, or assuming constant traffic) runs under the cap. "
          f"{n} runs per row; p = 1 rows: 100 runs.", "", HEADER]
    for r in (0.1, 1.0):
        scn = replace(base, realization=r, request_rate=base.spend_rate_at_p1 / r)
        for vname, kw in variants:
            for known in (True, False):
                c = SeasonalPacer(scn.center_view(), prior_mean=scn.spend_rate_at_p1,
                                  profile=prof if known else None)
                extra = dict(center_profile=prof) if known else {}
                res = simulate_with_backstop(scn, c, n, seed=23, rate_profile=prof, target=tgt, **extra, **kw)
                md.append(row(f"r = {r:g}, {vname}, profile {'known' if known else 'unknown'}", res, scn.budget))
            for known in (True, False):
                c = SeasonalPacer(scn.center_view(), prior_mean=scn.spend_rate_at_p1,
                                  profile=prof if known else None, pace_goal="time", half_life=600.0)
                extra = dict(center_profile=prof) if known else {}
                res = simulate_with_backstop(scn, c, n, seed=23, rate_profile=prof, **extra, **kw)
                md.append(row(f"r = {r:g}, {vname}, even in time, profile {'known' if known else 'unknown'}"
                              " (deviation from even spending)", res, scn.budget))
            res = simulate_with_backstop(scn, FullThrottle(), 100, seed=23, rate_profile=prof, **kw)
            md.append(row(f"r = {r:g}, {vname}, p = 1 throughout", res, scn.budget))
        md.append("|  |  |  |  |  |  |  |")
    md.append("")
    return md


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    quick = ap.parse_args().quick
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    (OUT / "probabilistic.md").write_text("\n".join(probabilistic(500 if quick else 4000)) + "\n")
    (OUT / "token-cap-a.md").write_text("\n".join(caps("reports", 100 if quick else 500)) + "\n")
    (OUT / "token-cap-b.md").write_text("\n".join(caps("grants", 100 if quick else 500)) + "\n")
    for f in ("probabilistic", "token-cap-a", "token-cap-b"):
        print((OUT / f"{f}.md").read_text())
    print(f"total {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
